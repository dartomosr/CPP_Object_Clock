import {readFileSync, writeFileSync} from 'node:fs';

// Small, dependency-free bundle for Wallpaper Engine's file-based web renderer.
const modules = ['clock', 'settings', 'backdrop', 'view', 'main'];
const parts = modules.map(name => {
    const source = readFileSync(new URL(`../scripts/${name}.js`, import.meta.url), 'utf8');
    return source.replace(/^import .+;\r?\n/gm, '').replace(/^export /gm, '');
});
const output = "// Generated by npm run build. Edit the source modules instead.\n(() => {\n'use strict';\n"
    + parts.join('\n') + '\nstartWallpaper(window, document);\n})();\n';
const target = new URL('../scripts/runtime.js', import.meta.url);
if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== output) throw new Error('runtime.js is out of date. Run npm run build.');
} else writeFileSync(target, output);
